class Flow:
 def __init__(self,name,height=1550):
  self.name=name;self.im=Image.new('RGB',(1500,height),'white');self.dr=ImageDraw.Draw(self.im);self.font=ImageFont.truetype(FONT,27);self.nodes={}
 def node(self,k,x,y,w,h,text,kind='process'):
  self.nodes[k]=(x,y,w,h)
  box=(x,y,x+w,y+h);color='#EDF3F6';line='#415666';dr=self.dr
  if kind=='connector':dr.ellipse(box,fill='white',outline=line,width=3)
  elif kind=='terminal':dr.rounded_rectangle(box,radius=h//2,fill=color,outline=line,width=3)
  elif kind=='decision':dr.polygon([(x+w/2,y),(x+w,y+h/2),(x+w/2,y+h),(x,y+h/2)],fill='#FFF4DC',outline=line,width=3)
  elif kind=='io':dr.polygon([(x+28,y),(x+w,y),(x+w-28,y+h),(x,y+h)],fill='#E9F3EC',outline=line,width=3)
  else:dr.rectangle(box,fill=color,outline=line,width=3)
  dr.multiline_text((x+w/2,y+h/2),text,font=self.font,fill='#14232D',anchor='mm',align='center',spacing=6)
 def edge(self,a,b,label='',side='down',route=None):
  x,y,w,h=self.nodes[a];xx,yy,ww,hh=self.nodes[b]
  if side=='right':st=(x+w,y+h/2);en=(xx,yy+hh/2)
  else:st=(x+w/2,y+h);en=(xx+ww/2,yy)
  pts=[st]+(route or ([] if st[0]==en[0] or st[1]==en[1] else [(st[0],(st[1]+en[1])/2),(en[0],(st[1]+en[1])/2)]))+[en]
  self.dr.line(pts,fill='#415666',width=3)
  ang=math.atan2(en[1]-pts[-2][1],en[0]-pts[-2][0]);self.dr.polygon([en,(en[0]-13*math.cos(ang-.5),en[1]-13*math.sin(ang-.5)),(en[0]-13*math.cos(ang+.5),en[1]-13*math.sin(ang+.5))],fill='#415666')
  if label:self.dr.text((st[0]+13,st[1]+10 if side=='down' else st[1]-38),label,font=self.font,fill='#14232D')
 def save(self):
  self.im.save(OUT/(self.name+'.png'));return OUT/(self.name+'.png')

